//! Client-to-server message encoding and input state (held keys/buttons, wheel accumulation).

use crate::keysym::keysym;
use rc_types::{MouseButton, SessionInput};
use std::collections::HashMap;
use std::sync::{Arc, Mutex};
use tracing::debug;

/// One screen of an ExtendedDesktopSize layout.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct Screen {
    pub id: u32,
    pub x: u16,
    pub y: u16,
    pub w: u16,
    pub h: u16,
    pub flags: u32,
}

/// State the reader learns from the server and the writer needs for its messages.
#[derive(Debug, Default)]
pub(crate) struct Shared {
    pub width: u16,
    pub height: u16,
    /// The server has sent an ExtendedDesktopSize rectangle, so SetDesktopSize is allowed.
    pub ext_desktop_size: bool,
    pub screens: Vec<Screen>,
}

pub(crate) type SharedRef = Arc<Mutex<Shared>>;

pub(crate) fn lock(shared: &SharedRef) -> std::sync::MutexGuard<'_, Shared> {
    shared.lock().unwrap_or_else(|e| e.into_inner())
}

pub(crate) fn set_pixel_format(buf: &mut Vec<u8>) {
    buf.extend_from_slice(&[0, 0, 0, 0]);
    buf.extend_from_slice(&crate::proto::OUR_PIXEL_FORMAT);
}

pub(crate) fn set_encodings(buf: &mut Vec<u8>, encodings: &[i32]) {
    buf.extend_from_slice(&[2, 0]);
    buf.extend_from_slice(&(encodings.len() as u16).to_be_bytes());
    for e in encodings {
        buf.extend_from_slice(&e.to_be_bytes());
    }
}

pub(crate) fn update_request(buf: &mut Vec<u8>, incremental: bool, w: u16, h: u16) {
    buf.extend_from_slice(&[3, u8::from(incremental), 0, 0, 0, 0]);
    buf.extend_from_slice(&w.to_be_bytes());
    buf.extend_from_slice(&h.to_be_bytes());
}

fn key_event(buf: &mut Vec<u8>, sym: u32, down: bool) {
    buf.extend_from_slice(&[4, u8::from(down), 0, 0]);
    buf.extend_from_slice(&sym.to_be_bytes());
}

fn pointer_event(buf: &mut Vec<u8>, mask: u8, x: u16, y: u16) {
    buf.extend_from_slice(&[5, mask]);
    buf.extend_from_slice(&x.to_be_bytes());
    buf.extend_from_slice(&y.to_be_bytes());
}

/// ClientCutText is Latin-1 only; anything else becomes '?'.
pub(crate) fn to_latin1(text: &str) -> Vec<u8> {
    text.chars().map(|c| if (c as u32) <= 0xff { c as u8 } else { b'?' }).collect()
}

fn client_cut_text(buf: &mut Vec<u8>, text: &str) {
    let bytes = to_latin1(text);
    buf.extend_from_slice(&[6, 0, 0, 0]);
    buf.extend_from_slice(&(bytes.len() as u32).to_be_bytes());
    buf.extend_from_slice(&bytes);
}

fn set_desktop_size(buf: &mut Vec<u8>, w: u16, h: u16, screens: &[Screen]) {
    buf.extend_from_slice(&[251, 0]);
    buf.extend_from_slice(&w.to_be_bytes());
    buf.extend_from_slice(&h.to_be_bytes());
    buf.extend_from_slice(&[screens.len() as u8, 0]);
    for s in screens {
        buf.extend_from_slice(&s.id.to_be_bytes());
        for v in [s.x, s.y, s.w, s.h] {
            buf.extend_from_slice(&v.to_be_bytes());
        }
        buf.extend_from_slice(&s.flags.to_be_bytes());
    }
}

const WHEEL_UP: u8 = 1 << 3; // button 4
const WHEEL_DOWN: u8 = 1 << 4; // button 5
const WHEEL_LEFT: u8 = 1 << 5; // button 6
const WHEEL_RIGHT: u8 = 1 << 6; // button 7
/// Most wheel clicks generated by a single Wheel input.
const MAX_NOTCHES: f32 = 30.0;

pub(crate) struct InputState {
    view_only: bool,
    buttons: u8,
    x: u16,
    y: u16,
    wheel_x: f32,
    wheel_y: f32,
    /// Keysym sent for each physical key that is down, so key-up releases the same one.
    keys: HashMap<String, u32>,
    warned_forward: bool,
}

impl InputState {
    pub fn new(view_only: bool) -> Self {
        InputState {
            view_only,
            buttons: 0,
            x: 0,
            y: 0,
            wheel_x: 0.0,
            wheel_y: 0.0,
            keys: HashMap::new(),
            warned_forward: false,
        }
    }

    fn set_pos(&mut self, x: u16, y: u16, shared: &SharedRef) {
        let s = lock(shared);
        self.x = x.min(s.width.saturating_sub(1));
        self.y = y.min(s.height.saturating_sub(1));
    }

    fn wheel_axis(buf: &mut Vec<u8>, acc: &mut f32, delta: f32, pos: u8, neg: u8, held: u8, x: u16, y: u16) {
        if !delta.is_finite() {
            return;
        }
        *acc = (*acc + delta).clamp(-MAX_NOTCHES, MAX_NOTCHES);
        while acc.abs() >= 1.0 {
            let bit = if *acc > 0.0 { pos } else { neg };
            *acc -= acc.signum();
            pointer_event(buf, held | bit, x, y);
            pointer_event(buf, held, x, y);
        }
    }

    /// Release every key and button we believe is held.
    pub fn release_all(&mut self, buf: &mut Vec<u8>) {
        for (_, sym) in self.keys.drain() {
            key_event(buf, sym, false);
        }
        if self.buttons != 0 {
            self.buttons = 0;
            pointer_event(buf, 0, self.x, self.y);
        }
        self.wheel_x = 0.0;
        self.wheel_y = 0.0;
    }

    /// Encode one input into `buf`. Returns true when the session should close.
    pub fn handle(&mut self, input: SessionInput, shared: &SharedRef, buf: &mut Vec<u8>) -> bool {
        match input {
            SessionInput::Close => return true,
            SessionInput::Refresh => {
                let (w, h) = {
                    let s = lock(shared);
                    (s.width, s.height)
                };
                debug!("full refresh requested");
                update_request(buf, false, w, h);
            }
            _ if self.view_only => {}
            SessionInput::PointerMove { x, y } => {
                self.set_pos(x, y, shared);
                pointer_event(buf, self.buttons, self.x, self.y);
            }
            SessionInput::PointerButton { button, down, x, y } => {
                self.set_pos(x, y, shared);
                let bit = match button {
                    MouseButton::Left => 1,
                    MouseButton::Middle => 2,
                    MouseButton::Right => 4,
                    MouseButton::Back => 1 << 7, // X11 button 8
                    MouseButton::Forward => {
                        // X11 button 9 does not fit in the 8-bit RFB button mask.
                        if !self.warned_forward {
                            self.warned_forward = true;
                            debug!("the Forward mouse button cannot be sent over RFB; ignoring");
                        }
                        0
                    }
                };
                if down {
                    self.buttons |= bit;
                } else {
                    self.buttons &= !bit;
                }
                pointer_event(buf, self.buttons, self.x, self.y);
            }
            SessionInput::Wheel { dx, dy, x, y } => {
                self.set_pos(x, y, shared);
                let (held, x, y) = (self.buttons, self.x, self.y);
                Self::wheel_axis(buf, &mut self.wheel_y, dy, WHEEL_UP, WHEEL_DOWN, held, x, y);
                Self::wheel_axis(buf, &mut self.wheel_x, dx, WHEEL_RIGHT, WHEEL_LEFT, held, x, y);
            }
            SessionInput::Key { code, key, down } => {
                // Identify the physical key by `code`; fall back to `key` if the front end has none.
                let id = if code.is_empty() { format!("key:{key}") } else { code.clone() };
                if down {
                    let Some(sym) = keysym(&code, &key) else {
                        debug!(code = %code, "no keysym for this key; ignoring");
                        return false;
                    };
                    if let Some(old) = self.keys.insert(id, sym) {
                        if old != sym {
                            key_event(buf, old, false);
                        }
                    }
                    key_event(buf, sym, true);
                } else if let Some(sym) = self.keys.remove(&id) {
                    key_event(buf, sym, false);
                }
            }
            SessionInput::ReleaseAll => self.release_all(buf),
            SessionInput::Clipboard(text) => {
                debug!(chars = text.chars().count(), "sending clipboard to the server");
                client_cut_text(buf, &text);
            }
            SessionInput::Resize { width, height } => {
                let s = lock(shared);
                if !s.ext_desktop_size {
                    debug!(width, height, "server does not support SetDesktopSize; ignoring resize request");
                } else if width == 0 || height == 0 {
                    debug!("ignoring resize request with a zero dimension");
                } else if (width, height) != (s.width, s.height) {
                    // Keep the first screen's identity and make it cover the new framebuffer.
                    let first = s.screens.first().copied();
                    let screen = Screen {
                        id: first.map_or(1, |f| f.id),
                        x: 0,
                        y: 0,
                        w: width,
                        h: height,
                        flags: first.map_or(0, |f| f.flags),
                    };
                    debug!(width, height, "sending SetDesktopSize");
                    set_desktop_size(buf, width, height, &[screen]);
                }
            }
        }
        false
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn shared(w: u16, h: u16) -> SharedRef {
        Arc::new(Mutex::new(Shared { width: w, height: h, ..Default::default() }))
    }
    fn feed(st: &mut InputState, sh: &SharedRef, input: SessionInput) -> Vec<u8> {
        let mut buf = Vec::new();
        assert!(!st.handle(input, sh, &mut buf));
        buf
    }
    fn key(code: &str, key: &str, down: bool) -> SessionInput {
        SessionInput::Key { code: code.into(), key: key.into(), down }
    }

    #[test]
    fn pointer_buttons_and_clamping() {
        let sh = shared(100, 50);
        let mut st = InputState::new(false);
        assert_eq!(feed(&mut st, &sh, SessionInput::PointerMove { x: 10, y: 500 }), [5, 0, 0, 10, 0, 49]);
        let b = |button, down| SessionInput::PointerButton { button, down, x: 258, y: 3 };
        assert_eq!(feed(&mut st, &sh, b(MouseButton::Left, true)), [5, 1, 0, 99, 0, 3]);
        assert_eq!(feed(&mut st, &sh, b(MouseButton::Right, true))[1], 5);
        assert_eq!(feed(&mut st, &sh, b(MouseButton::Middle, true))[1], 7);
        assert_eq!(feed(&mut st, &sh, b(MouseButton::Left, false))[1], 6);
        // ReleaseAll lets go of the remaining buttons.
        assert_eq!(feed(&mut st, &sh, SessionInput::ReleaseAll), [5, 0, 0, 99, 0, 3]);
        assert!(feed(&mut st, &sh, SessionInput::ReleaseAll).is_empty());
    }

    #[test]
    fn wheel_accumulates_fractions() {
        let sh = shared(100, 100);
        let mut st = InputState::new(false);
        let w = |dx, dy| SessionInput::Wheel { dx, dy, x: 1, y: 2 };
        assert!(feed(&mut st, &sh, w(0.0, 0.4)).is_empty());
        assert!(feed(&mut st, &sh, w(0.0, 0.4)).is_empty());
        // third 0.4 crosses 1.0: one wheel-up click (button 4 press + release)
        assert_eq!(feed(&mut st, &sh, w(0.0, 0.4)), [5, 8, 0, 1, 0, 2, 5, 0, 0, 1, 0, 2]);
        // two notches down
        let out = feed(&mut st, &sh, w(0.0, -2.2));
        assert_eq!(out.len(), 24);
        assert_eq!((out[1], out[7], out[13], out[19]), (16, 0, 16, 0));
        // horizontal: right = button 7, left = button 6
        assert_eq!(feed(&mut st, &sh, w(1.0, 0.0))[1], 64);
        assert_eq!(feed(&mut st, &sh, w(-1.0, 0.0))[1], 32);
        // NaN and huge values are harmless
        assert!(feed(&mut st, &sh, w(f32::NAN, f32::NAN)).is_empty());
        assert!(feed(&mut st, &sh, w(0.0, 1e9)).len() <= 12 * 31);
    }

    #[test]
    fn key_release_uses_the_keysym_that_was_pressed() {
        let sh = shared(10, 10);
        let mut st = InputState::new(false);
        assert_eq!(feed(&mut st, &sh, key("ShiftLeft", "Shift", true)), [4, 1, 0, 0, 0, 0, 0xff, 0xe1]);
        assert_eq!(feed(&mut st, &sh, key("KeyA", "A", true)), [4, 1, 0, 0, 0, 0, 0, 0x41]);
        assert_eq!(feed(&mut st, &sh, key("ShiftLeft", "Shift", false)), [4, 0, 0, 0, 0, 0, 0xff, 0xe1]);
        // Shift went up first, so the browser now reports "a": still release 'A'.
        assert_eq!(feed(&mut st, &sh, key("KeyA", "a", false)), [4, 0, 0, 0, 0, 0, 0, 0x41]);
        // A stray key-up is ignored.
        assert!(feed(&mut st, &sh, key("KeyA", "a", false)).is_empty());
        // Unicode keysym
        assert_eq!(feed(&mut st, &sh, key("KeyE", "€", true)), [4, 1, 0, 0, 0x01, 0x00, 0x20, 0xac]);
        // Same physical key now produces another symbol without a key-up: old one is released.
        assert_eq!(
            feed(&mut st, &sh, key("KeyE", "e", true)),
            [4, 0, 0, 0, 0x01, 0x00, 0x20, 0xac, 4, 1, 0, 0, 0, 0, 0, 0x65]
        );
        // Auto-repeat just repeats the press.
        assert_eq!(feed(&mut st, &sh, key("KeyE", "e", true)), [4, 1, 0, 0, 0, 0, 0, 0x65]);
        feed(&mut st, &sh, key("MetaLeft", "Meta", true));
        let out = feed(&mut st, &sh, SessionInput::ReleaseAll);
        assert_eq!(out.len(), 16);
        assert!(out.chunks(8).all(|c| c[..2] == [4, 0]));
        let mut syms: Vec<u32> = out.chunks(8).map(|c| u32::from_be_bytes(c[4..8].try_into().unwrap())).collect();
        syms.sort();
        assert_eq!(syms, [0x65, 0xffeb]);
        assert!(feed(&mut st, &sh, SessionInput::ReleaseAll).is_empty());
    }

    #[test]
    fn clipboard_is_latin1() {
        let sh = shared(10, 10);
        let mut st = InputState::new(false);
        let out = feed(&mut st, &sh, SessionInput::Clipboard("né€!".into()));
        assert_eq!(out, [6, 0, 0, 0, 0, 0, 0, 4, b'n', 0xe9, b'?', b'!']);
    }

    #[test]
    fn view_only_drops_input_but_not_refresh_or_close() {
        let sh = shared(640, 480);
        let mut st = InputState::new(true);
        assert!(feed(&mut st, &sh, SessionInput::PointerMove { x: 1, y: 1 }).is_empty());
        assert!(feed(&mut st, &sh, key("KeyA", "a", true)).is_empty());
        assert!(feed(&mut st, &sh, SessionInput::Clipboard("x".into())).is_empty());
        assert!(feed(&mut st, &sh, SessionInput::Wheel { dx: 0.0, dy: 3.0, x: 0, y: 0 }).is_empty());
        assert_eq!(feed(&mut st, &sh, SessionInput::Refresh), [3, 0, 0, 0, 0, 0, 2, 128, 1, 224]);
        assert!(st.handle(SessionInput::Close, &sh, &mut Vec::new()));
    }

    #[test]
    fn resize_needs_server_support() {
        let sh = shared(640, 480);
        let mut st = InputState::new(false);
        assert!(feed(&mut st, &sh, SessionInput::Resize { width: 800, height: 600 }).is_empty());
        {
            let mut s = lock(&sh);
            s.ext_desktop_size = true;
            s.screens = vec![Screen { id: 0x11223344, x: 0, y: 0, w: 640, h: 480, flags: 7 }];
        }
        let out = feed(&mut st, &sh, SessionInput::Resize { width: 800, height: 600 });
        assert_eq!(
            out,
            [251, 0, 3, 32, 2, 88, 1, 0, 0x11, 0x22, 0x33, 0x44, 0, 0, 0, 0, 3, 32, 2, 88, 0, 0, 0, 7]
        );
        assert!(feed(&mut st, &sh, SessionInput::Resize { width: 640, height: 480 }).is_empty());
    }
}
